def calculate_indicators(df):
    df = df.copy()
    df["EMA_fast"] = df["Close"].ewm(span=EMA_FAST, adjust=False).mean()
    df["EMA_slow"] = df["Close"].ewm(span=EMA_SLOW, adjust=False).mean()
    delta = df["Close"].diff()
    gain = delta.where(delta > 0, 0.0)
    loss = -delta.where(delta < 0, 0.0)
    avg_gain = gain.ewm(com=RSI_PERIOD - 1, min_periods=RSI_PERIOD).mean()
    avg_loss = loss.ewm(com=RSI_PERIOD - 1, min_periods=RSI_PERIOD).mean()
    rs = avg_gain / avg_loss
    df["RSI"] = 100 - (100 / (1 + rs))
    ema_f = df["Close"].ewm(span=MACD_FAST, adjust=False).mean()
    ema_s = df["Close"].ewm(span=MACD_SLOW, adjust=False).mean()
    df["MACD_line"] = ema_f - ema_s
    df["MACD_signal"] = df["MACD_line"].ewm(span=MACD_SIGNAL, adjust=False).mean()
    df["MACD_hist"] = df["MACD_line"] - df["MACD_signal"]
    df["BB_middle"] = df["Close"].rolling(BB_PERIOD).mean()
    bb_std = df["Close"].rolling(BB_PERIOD).std()
    df["BB_upper"] = df["BB_middle"] + BB_STD * bb_std
    df["BB_lower"] = df["BB_middle"] - BB_STD * bb_std
    df["Volume_MA"] = df["Volume"].rolling(VOLUME_MA_PERIOD).mean()
    return df


def generate_signals(df):
    df = df.copy()
    ema_bull = df["EMA_fast"] > df["EMA_slow"]
    rsi_buy = (df["RSI"] >= RSI_BUY_RANGE[0]) & (df["RSI"] <= RSI_BUY_RANGE[1])
    macd_bull = df["MACD_hist"] > 0
    bb_not_upper = df["Close"] < df["BB_upper"] * 0.99
    vol_above = df["Volume"] > df["Volume_MA"]
    buy_score = (ema_bull.astype(int) + rsi_buy.astype(int) +
                 macd_bull.astype(int) + bb_not_upper.astype(int) +
                 vol_above.astype(int)) / 5

    ema_bear = df["EMA_fast"] < df["EMA_slow"]
    rsi_sell = (df["RSI"] >= RSI_SELL_RANGE[0]) & (df["RSI"] <= RSI_SELL_RANGE[1])
    macd_bear = df["MACD_hist"] < 0
    bb_not_lower = df["Close"] > df["BB_lower"] * 1.01
    sell_score = (ema_bear.astype(int) + rsi_sell.astype(int) +
                  macd_bear.astype(int) + bb_not_lower.astype(int) +
                  vol_above.astype(int)) / 5

    df["Signal"] = 0
    df.loc[buy_score >= SIGNAL_THRESHOLD, "Signal"] = 1
    df.loc[sell_score >= SIGNAL_THRESHOLD, "Signal"] = -1
    return df


def run_backtest(df, symbol, initial_capital=INITIAL_CAPITAL):
    df = df.copy().dropna()
    capital = initial_capital
    position = 0
    entry_price = 0.0
    entry_date = None
    portfolio_values = []
    trades = []

    for i in range(len(df)):
        row = df.iloc[i]
        date = df.index[i]
        price = row["Close"]
        signal = row["Signal"]

        if signal == 1 and position == 0:
            buy_price = price * (1 + SLIPPAGE_PCT)
            investable = capital * POSITION_SIZE_PCT
            commission = investable * COMMISSION_PCT
            shares = int((investable - commission) / buy_price)
            if shares > 0:
                cost = shares * buy_price + commission
                capital -= cost
                position = shares
                entry_price = buy_price
                entry_date = date

        elif signal == -1 and position > 0:
            sell_price = price * (1 - SLIPPAGE_PCT)
            revenue = position * sell_price
            commission = revenue * COMMISSION_PCT
            capital += revenue - commission
            pnl = (sell_price - entry_price) * position - commission
            pnl_pct = (sell_price / entry_price - 1) * 100
            holding_days = (date - entry_date).days if entry_date else 0
            trades.append({
                "Symbol": symbol, "Entry_Date": entry_date, "Exit_Date": date,
                "Entry_Price": round(entry_price, 2), "Exit_Price": round(sell_price, 2),
                "Shares": position, "PnL": round(pnl, 2), "PnL_Pct": round(pnl_pct, 2),
                "Holding_Days": holding_days, "Win": pnl > 0,
            })
            position = 0
            entry_price = 0.0
            entry_date = None

        portfolio_val = capital + position * price if position > 0 else capital
        portfolio_values.append(portfolio_val)

    df["Portfolio"] = portfolio_values
    df["BuyHold"] = initial_capital * (df["Close"] / df["Close"].iloc[0])
    return df, trades


def calculate_metrics(df, trades, initial_capital=INITIAL_CAPITAL):
    portfolio = df["Portfolio"].values
    buyhold = df["BuyHold"].values
    n_days = len(df)
    n_years = n_days / 252

    total_return = (portfolio[-1] / initial_capital - 1) * 100
    bh_return = (buyhold[-1] / initial_capital - 1) * 100
    cagr = ((portfolio[-1] / initial_capital) ** (1 / n_years) - 1) * 100 if n_years > 0 else 0.0
    bh_cagr = ((buyhold[-1] / initial_capital) ** (1 / n_years) - 1) * 100 if n_years > 0 else 0.0

    daily_returns = pd.Series(portfolio).pct_change().dropna()
    sharpe = ((daily_returns.mean() - RISK_FREE_RATE/252) / daily_returns.std() * np.sqrt(252)) if daily_returns.std() > 0 else 0.0
    downside = daily_returns[daily_returns < 0]
    sortino = ((daily_returns.mean() - RISK_FREE_RATE/252) / downside.std() * np.sqrt(252)) if len(downside) > 0 and downside.std() > 0 else 0.0

    peak = pd.Series(portfolio).cummax()
    drawdown = (pd.Series(portfolio) - peak) / peak * 100
    max_dd = drawdown.min()
    calmar = cagr / abs(max_dd) if max_dd != 0 else 0.0

    n_trades = len(trades)
    if n_trades > 0:
        wins = [t for t in trades if t["Win"]]
        losses = [t for t in trades if not t["Win"]]
        win_rate = len(wins) / n_trades * 100
        avg_win = np.mean([t["PnL_Pct"] for t in wins]) if wins else 0.0
        avg_loss = np.mean([t["PnL_Pct"] for t in losses]) if losses else 0.0
        total_win_pnl = sum(t["PnL"] for t in wins)
        total_loss_pnl = abs(sum(t["PnL"] for t in losses))
        profit_factor = total_win_pnl / total_loss_pnl if total_loss_pnl > 0 else float("inf")
        avg_holding = np.mean([t["Holding_Days"] for t in trades])
        best_trade = max(t["PnL_Pct"] for t in trades)
        worst_trade = min(t["PnL_Pct"] for t in trades)
    else:
        win_rate = avg_win = avg_loss = profit_factor = avg_holding = 0.0
        best_trade = worst_trade = 0.0

    volatility = daily_returns.std() * np.sqrt(252) * 100

    metrics = {
        "Total Return (%)": round(total_return, 2),
        "Buy & Hold Return (%)": round(bh_return, 2),
        "CAGR (%)": round(cagr, 2),
        "B&H CAGR (%)": round(bh_cagr, 2),
        "Sharpe Ratio": round(sharpe, 2),
        "Sortino Ratio": round(sortino, 2),
        "Max Drawdown (%)": round(max_dd, 2),
        "Calmar Ratio": round(calmar, 2),
        "Volatility (%)": round(volatility, 2),
        "Total Trades": n_trades,
        "Win Rate (%)": round(win_rate, 2),
        "Avg Win (%)": round(avg_win, 2),
        "Avg Loss (%)": round(avg_loss, 2),
        "Profit Factor": round(profit_factor, 2),
        "Best Trade (%)": round(best_trade, 2),
        "Worst Trade (%)": round(worst_trade, 2),
        "Avg Holding (days)": round(avg_holding, 1),
        "Final Capital ($)": round(portfolio[-1], 2),
        "Starting Capital ($)": initial_capital,
    }
    return metrics, drawdown


