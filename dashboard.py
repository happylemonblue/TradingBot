def run_backtest_sim(df, sym, ic):
    df=df.copy().dropna(); cap=ic; pos=0; ep=0.0; ed=None; pv=[]; tr=[]
    for i in range(len(df)):
        r=df.iloc[i]; d=df.index[i]; p=r["Close"]; s=r["Signal"]
        if s==1 and pos==0:
            bp=p*(1+SLIPPAGE_PCT); inv=cap*POSITION_SIZE_PCT; cm=inv*COMMISSION_PCT; sh=int((inv-cm)/bp)
            if sh>0: cap-=sh*bp+cm; pos=sh; ep=bp; ed=d
        elif s==-1 and pos>0:
            sp=p*(1-SLIPPAGE_PCT); rv=pos*sp; cm=rv*COMMISSION_PCT; cap+=rv-cm
            pnl=(sp-ep)*pos-cm; pp=(sp/ep-1)*100; hd=(d-ed).days if ed else 0
            tr.append({"Symbol":sym,"Entry Date":str(ed)[:10],"Exit Date":str(d)[:10],"Entry Price":round(ep,2),
                "Exit Price":round(sp,2),"Shares":pos,"P&L ($)":round(pnl,2),"P&L (%)":round(pp,2),"Days Held":hd,"Result":"WIN" if pnl>0 else "LOSS"})
            pos=0; ep=0.0; ed=None
        pv.append(cap+pos*p if pos>0 else cap)
    df["Portfolio"]=pv; df["BuyHold"]=ic*(df["Close"]/df["Close"].iloc[0])
    return df, tr

def bt_metrics(df, tr, ic):
    p=df["Portfolio"].values; bh=df["BuyHold"].values; n=len(df); ny=n/252
    tr2=(p[-1]/ic-1)*100; bhr=(bh[-1]/ic-1)*100
    cagr=((p[-1]/ic)**(1/ny)-1)*100 if ny>0 else 0; bhc=((bh[-1]/ic)**(1/ny)-1)*100 if ny>0 else 0
    dr=pd.Series(p).pct_change().dropna()
    sh=((dr.mean()-RISK_FREE_RATE/252)/dr.std()*np.sqrt(252)) if dr.std()>0 else 0
    ds=dr[dr<0]; so=((dr.mean()-RISK_FREE_RATE/252)/ds.std()*np.sqrt(252)) if len(ds)>0 and ds.std()>0 else 0
    pk=pd.Series(p).cummax(); dd=(pd.Series(p)-pk)/pk*100; mdd=dd.min()
    cal=cagr/abs(mdd) if mdd!=0 else 0; nt=len(tr)
    if nt>0:
        w=[t for t in tr if t["Result"]=="WIN"]; l=[t for t in tr if t["Result"]=="LOSS"]
        wr=len(w)/nt*100; aw=np.mean([t["P&L (%)"] for t in w]) if w else 0; al=np.mean([t["P&L (%)"] for t in l]) if l else 0
        twp=sum(t["P&L ($)"] for t in w); tlp=abs(sum(t["P&L ($)"] for t in l))
        pf=twp/tlp if tlp>0 else float("inf"); ah=np.mean([t["Days Held"] for t in tr])
        bt=max(t["P&L (%)"] for t in tr); wt=min(t["P&L (%)"] for t in tr)
    else: wr=aw=al=pf=ah=bt=wt=0.0
    vol=dr.std()*np.sqrt(252)*100
    return {"Total Return (%)":round(tr2,2),"Buy & Hold Return (%)":round(bhr,2),"CAGR (%)":round(cagr,2),"B&H CAGR (%)":round(bhc,2),
        "Sharpe Ratio":round(sh,2),"Sortino Ratio":round(so,2),"Max Drawdown (%)":round(mdd,2),"Calmar Ratio":round(cal,2),
        "Volatility (%)":round(vol,2),"Total Trades":nt,"Win Rate (%)":round(wr,2),"Avg Win (%)":round(aw,2),
        "Avg Loss (%)":round(al,2),"Profit Factor":round(pf,2),"Best Trade (%)":round(bt,2),"Worst Trade (%)":round(wt,2),
        "Avg Holding (days)":round(ah,1),"Final Capital ($)":round(p[-1],2),"Starting Capital ($)":ic}, dd

