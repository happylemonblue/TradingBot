def generate_backtest_signals(df):
    df = df.copy()
    eb=df["EMA_fast"]>df["EMA_slow"]; rb=(df["RSI"]>=40)&(df["RSI"]<=70); mb=df["MACD_hist"]>0
    bbu=df["Close"]<df["BB_upper"]*0.99; va=df["Volume"]>df["Volume_MA"]
    vb=df["Close"]>df["VWAP"]; ct=df[["Senkou_A","Senkou_B"]].max(axis=1)
    cb=df[["Senkou_A","Senkou_B"]].min(axis=1); ib=(df["Close"]>ct)&(df["Tenkan"]>df["Kijun"])
    sb=df["ST_Direction"]==1
    bsc=(eb.astype(int)+rb.astype(int)+mb.astype(int)+bbu.astype(int)+va.astype(int)+vb.astype(int)+ib.astype(int)+sb.astype(int))/8
    ee=df["EMA_fast"]<df["EMA_slow"]; rs=(df["RSI"]>=30)&(df["RSI"]<=60); ms=df["MACD_hist"]<0
    bbl=df["Close"]>df["BB_lower"]*1.01; vs=df["Close"]<df["VWAP"]
    ise=(df["Close"]<cb)&(df["Tenkan"]<df["Kijun"]); ss=df["ST_Direction"]==-1
    ssc=(ee.astype(int)+rs.astype(int)+ms.astype(int)+bbl.astype(int)+va.astype(int)+vs.astype(int)+ise.astype(int)+ss.astype(int))/8
    df["Signal"]=0; df.loc[bsc>=SIGNAL_THRESHOLD,"Signal"]=1; df.loc[ssc>=SIGNAL_THRESHOLD,"Signal"]=-1
