def plot_trade_distribution(trades, symbol):
    if not trades:
        return
    pnls = [t["PnL_Pct"] for t in trades]
    wins = [p for p in pnls if p > 0]
    losses = [p for p in pnls if p <= 0]
    fig, ax = plt.subplots(figsize=(10, 5))
    all_bins = np.linspace(min(pnls)-1, max(pnls)+1, 20)
    if wins:
        ax.hist(wins, bins=all_bins, color="#4CAF50", alpha=0.7, label=f"Wins ({len(wins)})", edgecolor="white")
    if losses:
        ax.hist(losses, bins=all_bins, color="#F44336", alpha=0.7, label=f"Losses ({len(losses)})", edgecolor="white")
    ax.axvline(0, color="#333", linewidth=1.5)
    ax.axvline(np.mean(pnls), color="#2196F3", linewidth=1.5, linestyle="--", label=f"Avg: {np.mean(pnls):.2f}%")
    ax.set_title(f"Trade P&L Distribution - {symbol}", fontsize=13, fontweight="bold")
    ax.set_xlabel("Return (%)")
    ax.set_ylabel("Number of Trades")
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig("backtest_distribution.png", dpi=150)
    plt.close()
    print("  Chart saved: backtest_distribution.png")


def plot_monthly_returns(df, symbol):
    daily_ret = df["Portfolio"].pct_change()
    monthly_ret = daily_ret.resample("ME").apply(lambda x: (1 + x).prod() - 1) * 100
    monthly_df = pd.DataFrame({"Year": monthly_ret.index.year, "Month": monthly_ret.index.month, "Return": monthly_ret.values})
    pivot = monthly_df.pivot_table(values="Return", index="Year", columns="Month", aggfunc="sum")
    month_names = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"]
    pivot.columns = [month_names[c-1] for c in pivot.columns]
    fig, ax = plt.subplots(figsize=(12, max(3, len(pivot)*1.0)))
    vals = pivot.values[~np.isnan(pivot.values)]
    vmax = max(abs(vals.min()), abs(vals.max()), 5) if len(vals) > 0 else 5
    im = ax.imshow(pivot.values, cmap=plt.cm.RdYlGn, aspect="auto", vmin=-vmax, vmax=vmax)
    ax.set_xticks(range(len(pivot.columns)))
    ax.set_xticklabels(pivot.columns, fontsize=10)
    ax.set_yticks(range(len(pivot.index)))
    ax.set_yticklabels(pivot.index, fontsize=10)
    for i in range(len(pivot.index)):
        for j in range(len(pivot.columns)):
            val = pivot.values[i, j]
            if not np.isnan(val):
                color = "white" if abs(val) > vmax*0.6 else "black"
                ax.text(j, i, f"{val:.1f}%", ha="center", va="center", fontsize=9, fontweight="bold", color=color)
    ax.set_title(f"Monthly Returns Heatmap (%) - {symbol}", fontsize=13, fontweight="bold")
    plt.colorbar(im, ax=ax, label="Return (%)", shrink=0.8)
    plt.tight_layout()
    plt.savefig("backtest_monthly_returns.png", dpi=150)
    plt.close()
    print("  Chart saved: backtest_monthly_returns.png")


