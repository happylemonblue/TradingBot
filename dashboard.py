def compute_signal_score(df, threshold):
    if len(df) < 55: return "HOLD", 0.0
    la = df.iloc[-1]
    eb=la["EMA_fast"]>la["EMA_slow"]; ro=40<=la["RSI"]<=70; mo=la["MACD_hist"]>0
    bo=la["Close"]<la["BB_upper"]*0.99; vo=la["Volume"]>la["Volume_MA"] if la["Volume_MA"]>0 else False
    vb=la["Close"]>la["VWAP"] if pd.notna(la["VWAP"]) else False
    iok=pd.notna(la["Senkou_A"]) and pd.notna(la["Senkou_B"])
    if iok:
        ib=(la["Close"]>max(la["Senkou_A"],la["Senkou_B"])) and (la["Tenkan"]>la["Kijun"])
        ise=(la["Close"]<min(la["Senkou_A"],la["Senkou_B"])) and (la["Tenkan"]<la["Kijun"])
    else: ib=False; ise=False
    stb=la["ST_Direction"]==1 if pd.notna(la["ST_Direction"]) else False
    sts=la["ST_Direction"]==-1 if pd.notna(la["ST_Direction"]) else False
    bs=sum([eb,ro,mo,bo,vo,vb,ib,stb])/8
    ee=not eb; rs=30<=la["RSI"]<=60; ms=la["MACD_hist"]<0; bbs=la["Close"]>la["BB_lower"]*1.01
    vs=la["Close"]<la["VWAP"] if pd.notna(la["VWAP"]) else False
    ss=sum([ee,rs,ms,bbs,vo,vs,ise,sts])/8
    if bs >= threshold: return "BUY", bs
    elif ss >= threshold: return "SELL", ss
    return "HOLD", max(bs, ss)

def quick_signal_with_levels(df, threshold, live_price=None):
    if len(df) < 55: return "HOLD", 0.0, {}
    sig, conf = compute_signal_score(df, threshold)
    la = df.iloc[-1]
    stv = la["Supertrend"] if pd.notna(la["Supertrend"]) else 0
    entry = round(live_price, 2) if live_price and live_price > 0 else round(la["Close"], 2)
    levels = {}
    if sig == "BUY":
        sl = round(stv,2) if (pd.notna(stv) and stv>0 and stv<entry) else round(la["BB_lower"],2)
        risk = entry-sl
        if risk<=0: risk=entry*0.02; sl=round(entry-risk,2)
        t1=round(la["BB_upper"],2); t2=round(entry+2*risk,2)
        levels={"entry":entry,"stop_loss":sl,"target_1":t1,"target_2":t2,"risk_pct":round((entry-sl)/entry*100,2),"rr":round((t1-entry)/risk,2) if risk>0 else 0}
    elif sig == "SELL":
        sl = round(stv,2) if (pd.notna(stv) and stv>0 and stv>entry) else round(la["BB_upper"],2)
        risk = sl-entry
        if risk<=0: risk=entry*0.02; sl=round(entry+risk,2)
        t1=round(la["BB_lower"],2); t2=round(entry-2*risk,2)
        levels={"entry":entry,"stop_loss":sl,"target_1":t1,"target_2":t2,"risk_pct":round((sl-entry)/entry*100,2),"rr":round((entry-t1)/risk,2) if risk>0 else 0}
    return sig, conf, levels

