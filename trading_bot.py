def save_signals(signals):
    history = []
    if os.path.exists(SIGNALS_LOG):
        try:
            with open(SIGNALS_LOG, "r") as f: history = json.load(f)
        except: history = []
    actionable = [s for s in signals if s["signal"] in ("BUY","SELL")]
    history.extend(actionable); history = history[-500:]
    with open(SIGNALS_LOG, "w") as f: json.dump(history, f, indent=2, default=str)
    logger.info(f"Saved {len(actionable)} signals")


def run_scan():
    global WATCHLIST, SIGNAL_THRESHOLD, SUPERTREND_ATR_PERIOD, SUPERTREND_MULTIPLIER
    WATCHLIST = load_watchlist()
    config = load_config()
    SIGNAL_THRESHOLD = config["signal_threshold"]
    SUPERTREND_ATR_PERIOD = config["supertrend_atr_period"]
    SUPERTREND_MULTIPLIER = config["supertrend_multiplier"]

    logger.info("=" * 60)
    logger.info(f"Scan at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    logger.info(f"Watchlist: {len(WATCHLIST)} | Threshold: {SIGNAL_THRESHOLD} ({int(SIGNAL_THRESHOLD*8)}/8)")
    logger.info(f"Supertrend: ATR={SUPERTREND_ATR_PERIOD}, Mult={SUPERTREND_MULTIPLIER}")
    logger.info("=" * 60)
    all_signals = []
    for symbol in WATCHLIST:
        try:
            logger.info(f"Scanning {symbol}...")
            df = yf.Ticker(symbol).history(period=DATA_PERIOD, interval=DATA_INTERVAL)
            if df.empty or len(df) < 55:
                logger.warning(f"{symbol}: Insufficient data"); continue
            df = calculate_indicators(df)
            sig = generate_signal(df, symbol)
            all_signals.append(sig)
            if sig["signal"] in ("BUY","SELL"):
                logger.info(f"{sig['signal']} -> {sig['symbol']} @ ${sig['price']} ({sig['confidence']:.0%})")
                print_signal(sig)
        except Exception as e:
            logger.error(f"Error {symbol}: {e}"); continue
    if all_signals:
        print_scan_summary(all_signals); save_signals(all_signals)
    logger.info(f"Done. {len(all_signals)} tickers. View: http://localhost:8501")
    return all_signals


