def main():
    parser = argparse.ArgumentParser(
        description="Trading Strategy Backtester v1.1 (SSL-patched)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python backtest_engine.py                       # SPY, 2 years
  python backtest_engine.py --symbol AAPL         # Apple, 2 years
  python backtest_engine.py --symbol NVDA --period 5y --capital 50000
  python backtest_engine.py --all                 # All 15 tickers
        """
    )
    parser.add_argument("--symbol", type=str, default="SPY", help="Ticker symbol (default: SPY)")
    parser.add_argument("--period", type=str, default="2y", help="Data period (default: 2y)")
    parser.add_argument("--capital", type=float, default=10000, help="Initial capital (default: 10000)")
    parser.add_argument("--all", action="store_true", help="Backtest entire watchlist")
    args = parser.parse_args()

    symbols = WATCHLIST if args.all else [args.symbol.upper()]
    all_metrics = []

    for sym in symbols:
        print(f"\n{'='*60}")
        print(f"  Backtesting: {sym} | Period: {args.period} | Capital: ${args.capital:,.2f}")
        print(f"{'='*60}")

        try:
            ticker = yf.Ticker(sym)
            df = ticker.history(period=args.period, interval="1d")

            if isinstance(df.columns, pd.MultiIndex):
                df.columns = df.columns.get_level_values(0)

            if df.empty or len(df) < 30:
                print(f"  Skipping {sym} - insufficient data ({len(df)} rows)")
                continue

            print(f"  Loaded {len(df)} bars: {df.index[0].strftime('%Y-%m-%d')} to {df.index[-1].strftime('%Y-%m-%d')}")

            df = calculate_indicators(df)
            df = generate_signals(df)

            buy_count = (df["Signal"] == 1).sum()
            sell_count = (df["Signal"] == -1).sum()
            print(f"  Signals found: {buy_count} BUY, {sell_count} SELL")

            df, trades = run_backtest(df, sym, args.capital)
            metrics, drawdown = calculate_metrics(df, trades, args.capital)
            metrics["Symbol"] = sym
            all_metrics.append(metrics)

            print_report(metrics, sym, args.period)

            if len(symbols) == 1:
                print("\n  Generating charts...")
                plot_equity_curve(df, metrics, sym)
                plot_drawdown(df, drawdown, sym)
                plot_signals_on_price(df, trades, sym)
                plot_trade_distribution(trades, sym)
                plot_monthly_returns(df, sym)

                if trades:
                    trades_exp = []
                    for t in trades:
                        te = t.copy()
                        te["Entry_Date"] = str(te["Entry_Date"])[:10]
                        te["Exit_Date"] = str(te["Exit_Date"])[:10]
                        trades_exp.append(te)
                    pd.DataFrame(trades_exp).to_csv("backtest_trades.csv", index=False)
                    print(f"  Trades exported: backtest_trades.csv ({len(trades)} trades)")

                pd.DataFrame([metrics]).to_csv("backtest_metrics.csv", index=False)
                df[["Close","Portfolio","BuyHold","Signal","RSI","MACD_hist"]].to_csv("backtest_daily.csv")
                print("  Metrics + daily data exported")

        except Exception as e:
            print(f"  ERROR on {sym}: {e}")
            continue

    if len(all_metrics) > 1:
        summary_df = pd.DataFrame(all_metrics)
        summary_df.to_csv("backtest_summary.csv", index=False)
        print(f"\n{'='*80}")
        print("  WATCHLIST BACKTEST SUMMARY")
        print(f"{'='*80}")
        display_cols = ["Symbol", "Total Return (%)", "CAGR (%)", "Sharpe Ratio",
                        "Max Drawdown (%)", "Win Rate (%)", "Profit Factor", "Total Trades"]
        avail_cols = [c for c in display_cols if c in summary_df.columns]
        print(summary_df[avail_cols].to_string(index=False))
        print(f"\n  Summary saved: backtest_summary.csv")

    print(f"\nDone!")


if __name__ == "__main__":
    main()
