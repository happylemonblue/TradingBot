    df["Senkou_A"] = ((df["Tenkan"] + df["Kijun"]) / 2).shift(ICHIMOKU_KIJUN)
    h52 = df["High"].rolling(ICHIMOKU_SENKOU_B).max(); l52 = df["Low"].rolling(ICHIMOKU_SENKOU_B).min()
